import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import {checkMusicTrack} from './check-story-film.mjs';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'track-lock-'));
const track='music.aac',file=path.join(root,track);
fs.writeFileSync(file,'original music bytes');
const sheet={music:{track}};
const lock={tool:'scripts/sound.py v2',music_track:{path:track,sha256:createHash('sha256').update(fs.readFileSync(file)).digest('hex')}};
test('the exact recorded track passes without touching it',()=>assert.deepEqual(checkMusicTrack({root,sheet,lock}),[]));
test('changing bytes at the same path invalidates a mix',()=>{fs.writeFileSync(file,'different music bytes');assert.match(checkMusicTrack({root,sheet,lock})[0],/bytes changed/);fs.writeFileSync(file,'original music bytes');});
test('a missing source fails instead of falling back to procedural music',()=>{assert.match(checkMusicTrack({root,sheet:{music:{track:'missing.aac'}},lock})[0],/missing/);});
test('a new v2 recorded-track mix cannot omit the digest',()=>assert.match(checkMusicTrack({root,sheet,lock:{tool:'scripts/sound.py v2'}})[0],/not hashed/));
test('procedural and already-delivered v1 mixes are left unchanged',()=>{assert.deepEqual(checkMusicTrack({root,sheet:{music:{}},lock:{tool:'scripts/sound.py v1'}}),[]);assert.deepEqual(checkMusicTrack({root,sheet,lock:{tool:'scripts/sound.py v1'}}),[]);});
test('a supplied digest is checked even on an otherwise legacy lock',()=>assert.match(checkMusicTrack({root,sheet,lock:{tool:'scripts/sound.py v1',music_track:{path:track,sha256:'bad'}}})[0],/bytes changed/));
process.on('exit',()=>fs.rmSync(root,{recursive:true,force:true}));
