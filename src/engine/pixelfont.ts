export const GLYPH_ROWS = 7;

/** The word as a grid of 0/1, one row per string of the result. */
export function wordBitmap(text: string): { width: number; rows: Uint8Array[] } {
  const cols: number[] = [];
  for (const ch of text) {
    const glyph = G[ch] ?? G[ch.toUpperCase()] ?? G["?"];
    if (cols.length > 0) cols.push(0);
    cols.push(...glyph);
  }
  const rows: Uint8Array[] = [];
  for (let y = 0; y < GLYPH_ROWS; y++) {
    rows.push(Uint8Array.from(cols, (c) => (c >> y) & 1));
  }
  return { width: cols.length, rows };
}

const CACHE = new Map<string, THREE.DataTexture>();

/**
 * White letters, a one-pixel black outline all round, and one more pixel of
 * black down-right as a drop shadow. Transparent elsewhere.
 */
export function wordTexture(text: string): THREE.DataTexture {
  const hit = CACHE.get(text);
  if (hit) return hit;

  const { width, rows } = wordBitmap(text);
  const pad = 2; // outline + shadow
  const w = width + pad * 2;
  const h = GLYPH_ROWS + pad * 2;
  const data = new Uint8Array(w * h * 4);
  const lit = (x: number, y: number) => x >= 0 && y >= 0 && x < width && y < GLYPH_ROWS && rows[y][x] === 1;

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const gx = x - pad;
      const gy = y - pad;
      let value = -1; // -1 clear, 0 black, 1 white
      if (lit(gx, gy)) value = 1;
      else {
        outer: for (let dy = -1; dy <= 1; dy++) {
          for (let dx = -1; dx <= 1; dx++) {
            if (lit(gx + dx, gy + dy)) {
              value = 0;
              break outer;
            }
          }
        }
        if (value < 0 && (lit(gx - 2, gy - 2) || lit(gx - 1, gy - 2) || lit(gx - 2, gy - 1))) value = 0;
      }
      // DataTexture row 0 is the BOTTOM of the image.
      const i = ((h - 1 - y) * w + x) * 4;
      if (value >= 0) {
        data[i] = data[i + 1] = data[i + 2] = value * 255;
        data[i + 3] = 255;
      }
    }
  }

  const tex = new THREE.DataTexture(data, w, h, THREE.RGBAFormat);
  tex.magFilter = THREE.NearestFilter;
  tex.minFilter = THREE.NearestFilter;
  tex.generateMipmaps = false;
  tex.needsUpdate = true;
  CACHE.set(text, tex);
  return tex;
}
